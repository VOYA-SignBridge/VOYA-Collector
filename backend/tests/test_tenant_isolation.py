class TestContainedRole:
    def test_cannot_disable_the_policy(self, app_conn):
        """The guarantee must not be self-revocable: if the application role
        could run this statement, every assertion above would be advisory."""
        with pytest.raises(psycopg2.errors.InsufficientPrivilege):
            with app_conn.cursor() as cur:
                cur.execute("ALTER TABLE samples DISABLE ROW LEVEL SECURITY")
        app_conn.rollback()

    def test_cannot_drop_the_policy(self, app_conn):
        with pytest.raises(psycopg2.errors.InsufficientPrivilege):
            with app_conn.cursor() as cur:
                cur.execute(f"DROP POLICY {rls.POLICY_NAME} ON samples")
        app_conn.rollback()

    def test_cannot_create_tables(self, app_conn):
        """A new table would arrive with no policy on it."""
        with pytest.raises(psycopg2.errors.InsufficientPrivilege):
            with app_conn.cursor() as cur:
                cur.execute("CREATE TABLE escape_hatch (id int)")
        app_conn.rollback()


