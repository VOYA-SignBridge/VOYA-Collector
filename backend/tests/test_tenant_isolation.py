class TestFailsClosed:
    @pytest.mark.parametrize("table", ["samples", "classes", "raw_uploads"])
    def test_unscoped_connection_reads_nothing(self, app_conn, table):
        """The central claim. An unscoped connection must see zero rows, not all
        rows: a code path someone forgot to scope then returns nothing and gets
        noticed, instead of returning everything and not getting noticed."""
        cur = _scoped(app_conn, None, False)
        cur.execute(f"SELECT count(*) FROM {table}")
        assert cur.fetchone()[0] == 0
        app_conn.rollback()

    def test_connection_that_never_set_the_guc_at_all_reads_nothing(self, app_conn):
        """Distinct from the case above: here no `set_config` runs, so the GUC is
        genuinely undefined rather than empty. `current_setting(x, true)` returns
        NULL, and NULL is not TRUE — which is why the missing_ok form is used."""
        with app_conn.cursor() as cur:
            cur.execute("SELECT count(*) FROM samples")
            assert cur.fetchone()[0] == 0
        app_conn.rollback()

    def test_unscoped_insert_is_rejected(self, app_conn):
        with pytest.raises(psycopg2.errors.InsufficientPrivilege):
            cur = _scoped(app_conn, None, False)
            cur.execute(
                "INSERT INTO samples(sample_uid, tenant_id) VALUES ('cccccccc01', %s)",
                (TENANT_A,),
            )
        app_conn.rollback()

    def test_empty_tenant_id_is_not_a_wildcard(self, app_conn):
        """`''` must behave as "no tenant", not as "match anything"."""
        cur = _scoped(app_conn, "", False)
        cur.execute("SELECT count(*) FROM samples")
        assert cur.fetchone()[0] == 0
        app_conn.rollback()

    def test_system_scope_must_be_exactly_on(self, app_conn):
        """Any other truthy-looking value must not open the gate."""
        for value in ("ON", "true", "1", "yes", " on"):
            cur = app_conn.cursor()
            cur.execute(
                rls._APPLY_SCOPE_SQL,
                (rls.SYSTEM_SCOPE_GUC, value, rls.TENANT_GUC, ""),
            )
            cur.execute("SELECT count(*) FROM samples")
            assert cur.fetchone()[0] == 0, f"{value!r} must not grant system scope"
            app_conn.rollback()


