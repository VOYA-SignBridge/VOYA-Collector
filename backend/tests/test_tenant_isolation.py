class _RecordingCursor:
    def __init__(self):
        self.calls = []

    def execute(self, sql, params=None):
        self.calls.append((sql, params))


class TestApplicationLayerEmitsScope:
    def test_apply_scope_reads_the_ambient_context(self):
        from app.tenant_context import system_scope, tenant_scope

        cur = _RecordingCursor()
        with tenant_scope("truong-b"):
            rls.apply_scope(cur)
        assert cur.calls[-1][1] == (rls.SYSTEM_SCOPE_GUC, "", rls.TENANT_GUC, "truong-b")

        with system_scope("test"):
            rls.apply_scope(cur)
        assert cur.calls[-1][1] == (
            rls.SYSTEM_SCOPE_GUC, rls.SYSTEM_SCOPE_ON, rls.TENANT_GUC, "",
        )

    def test_scope_sql_is_transaction_local(self):
        """`SET LOCAL` semantics, not `SET`. A plain SET persists on a pooled
        connection and leaks one tenant's context into the next request that
        borrows it — a defect that produces no error at all, just wrong data for
        one user."""
        assert rls._APPLY_SCOPE_SQL.count("true") == 2
        assert "set_config" in rls._APPLY_SCOPE_SQL

    @pytest.mark.parametrize("function", ["_cursor", "_fetch_all"])
    def test_every_metadata_query_binds_a_scope(self, function, monkeypatch):
        """Both database entry points must call apply_scope before anything else.

        Asserted by observing the call, not by reading the source: an assertion
        on source text passes whenever the words appear, including inside the
        comment that explains them.
        """
        import app.storage.metadata_db as mdb

        seen = []
        monkeypatch.setattr(mdb, "apply_scope", lambda cur: seen.append(cur))

        if function == "_cursor":
            with mdb._cursor() as cur:
                cur.execute("SELECT 1")
        else:
            mdb._fetch_all("SELECT 1 AS one")

        assert len(seen) == 1, f"{function} did not bind a tenant scope"


