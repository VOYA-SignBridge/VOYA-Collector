class TestWriteIsolation:
    def test_update_across_tenants_changes_nothing(self, app_conn):
        """The unfiltered UPDATE is the point: `update_sample_gdrive_url()` and
        `delete_sample()` in metadata_db carry no tenant filter to this day. The
        policy is what makes those safe without editing every one of them."""
        cur = _scoped(app_conn, TENANT_A)
        cur.execute("UPDATE samples SET storage_url = 'x' WHERE sample_uid = %s", (SAMPLE_B,))
        assert cur.rowcount == 0
        app_conn.commit()

        check = _scoped(app_conn, TENANT_B)
        check.execute("SELECT storage_url FROM samples WHERE sample_uid = %s", (SAMPLE_B,))
        assert check.fetchone()[0] is None
        app_conn.rollback()

    def test_delete_across_tenants_removes_nothing(self, app_conn):
        cur = _scoped(app_conn, TENANT_A)
        cur.execute("DELETE FROM samples WHERE sample_uid = %s", (SAMPLE_B,))
        assert cur.rowcount == 0
        app_conn.commit()

        check = _scoped(app_conn, TENANT_B)
        check.execute("SELECT count(*) FROM samples WHERE sample_uid = %s", (SAMPLE_B,))
        assert check.fetchone()[0] == 1
        app_conn.rollback()

    def test_blanket_delete_only_empties_the_current_tenant(self, app_conn):
        """A `DELETE FROM samples` with no WHERE at all — the worst plausible
        accident — must not be able to reach another tenant's rows."""
        cur = _scoped(app_conn, TENANT_A)
        cur.execute("DELETE FROM samples")
        assert cur.rowcount == 1
        app_conn.rollback()  # keep the fixture intact for later tests

    def test_cannot_insert_a_row_owned_by_another_tenant(self, app_conn):
        """WITH CHECK. Without it a tenant could write rows into another tenant's
        partition — invisible to itself afterwards, and undetectable from here."""
        with pytest.raises(psycopg2.errors.InsufficientPrivilege):
            cur = _scoped(app_conn, TENANT_A)
            cur.execute(
                "INSERT INTO samples(sample_uid, tenant_id) VALUES ('dddddddd01', %s)",
                (TENANT_B,),
            )
        app_conn.rollback()

    def test_cannot_move_a_row_to_another_tenant(self, app_conn):
        """UPDATE is checked by both clauses: USING picks the row, WITH CHECK
        vets the result. Equal predicates are what close this."""
        with pytest.raises(psycopg2.errors.InsufficientPrivilege):
            cur = _scoped(app_conn, TENANT_A)
            cur.execute(
                "UPDATE samples SET tenant_id = %s WHERE sample_uid = %s",
                (TENANT_B, SAMPLE_A),
            )
        app_conn.rollback()

    def test_insert_into_own_tenant_still_works(self, app_conn):
        """Negative control. If the policy rejected everything the tests above
        would all pass while the application was completely broken."""
        cur = _scoped(app_conn, TENANT_A)
        cur.execute(
            "INSERT INTO samples(sample_uid, tenant_id) VALUES ('eeeeeeee01', %s)",
            (TENANT_A,),
        )
        assert cur.rowcount == 1
        app_conn.rollback()


