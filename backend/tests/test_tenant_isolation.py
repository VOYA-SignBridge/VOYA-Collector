class TestReadIsolation:
    @pytest.mark.parametrize("table,key", [
        ("samples", "sample_uid"),
        ("classes", "class_uid"),
        ("raw_uploads", "upload_uid"),
    ])
    def test_a_sees_only_its_own_rows(self, app_conn, table, key):
        cur = _scoped(app_conn, TENANT_A)
        cur.execute(f"SELECT {key}, tenant_id FROM {table}")
        rows = cur.fetchall()
        assert rows, f"{table}: tenant A must see its own row"
        assert {r[1] for r in rows} == {TENANT_A}
        app_conn.rollback()

    def test_b_sees_only_its_own_rows(self, app_conn):
        cur = _scoped(app_conn, TENANT_B)
        cur.execute("SELECT sample_uid FROM samples")
        assert [r[0] for r in cur.fetchall()] == [SAMPLE_B]
        app_conn.rollback()

    def test_targeting_another_tenant_by_primary_key_returns_nothing(self, app_conn):
        """Not merely filtered — invisible. Knowing the id does not help."""
        cur = _scoped(app_conn, TENANT_A)
        cur.execute("SELECT sample_uid FROM samples WHERE sample_uid = %s", (SAMPLE_B,))
        assert cur.fetchone() is None
        app_conn.rollback()

    def test_aggregates_do_not_leak_counts(self, app_conn):
        """COUNT(*) is a read too — a leaked total is a leaked fact."""
        cur = _scoped(app_conn, TENANT_A)
        cur.execute("SELECT count(*) FROM samples")
        assert cur.fetchone()[0] == 1
        app_conn.rollback()

    def test_system_scope_sees_every_tenant(self, app_conn):
        cur = _scoped(app_conn, system=True)
        cur.execute("SELECT tenant_id FROM samples ORDER BY tenant_id")
        assert [r[0] for r in cur.fetchall()] == [TENANT_A, TENANT_B]
        app_conn.rollback()


