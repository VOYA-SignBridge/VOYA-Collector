def _admin_dsn() -> str:
    from app.config import settings
    from app.storage.postgres_connection import migration_dsn

    return migration_dsn() or settings.database_url


def _with_database(dsn: str, dbname: str) -> str:
    parts = urlsplit(dsn)
    return urlunsplit((parts.scheme, parts.netloc, f"/{dbname}", "", ""))


def _with_user(dsn: str, user: str, password: str) -> str:
    from urllib.parse import quote

    parts = urlsplit(dsn)
    host = parts.hostname or "postgres"
    netloc = f"{user}:{quote(password, safe='')}@{host}"
    if parts.port:
        netloc += f":{parts.port}"
    return urlunsplit((parts.scheme, netloc, parts.path, "", ""))


def _app_password() -> str:
    """Password for the contained role, from the environment or the repo .env.

    Read lazily rather than in conftest: only this suite needs it, and a
    deployment that has not provisioned the role should skip rather than fail.
    """
    password = os.getenv("VOYA_APP_DB_PASSWORD", "").strip()
    if password:
        return password
    from pathlib import Path

    envf = Path(__file__).resolve().parents[2] / ".env"
    if envf.exists():
        for line in envf.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line.startswith("VOYA_APP_DB_PASSWORD=") and not line.startswith("#"):
                return line.split("=", 1)[1].strip()
    return ""


@pytest.fixture(scope="module")
def scratch_db():
    """A throwaway database carrying the real schema and the real policies."""
    from app.cli.provision_db_roles import APP_ROLE, provision
    # `AUTHZ_DDL_STATEMENTS` phải có mặt, và nó không phải tuỳ chọn: từ PDM
    # v1.0, `rls.rls_ddl()` cài chính sách cho cả tám bảng của mặt phẳng phân
    # quyền. Dựng schema mà thiếu chúng thì vòng lặp `rls_ddl()` bên dưới —
    # vòng lặp CỐ Ý không nuốt lỗi, vì nó chính là thứ đang được kiểm — sẽ
    # chết với `relation "workspaces" does not exist`.
    from app.storage.authz_schema import AUTHZ_DDL_STATEMENTS
    from app.storage.metadata_db import DDL_STATEMENTS, MIGRATION_STATEMENTS

    password = _app_password()
    if not password:
        pytest.skip("VOYA_APP_DB_PASSWORD not set — run app.cli.provision_db_roles first")

    admin_dsn = _admin_dsn()
    dbname = f"voya_rls_proof_{uuid.uuid4().hex[:8]}"

    try:
        bootstrap = psycopg2.connect(admin_dsn, connect_timeout=5)
    except Exception as exc:  # pragma: no cover - environment dependent
        pytest.skip(f"no live Postgres: {exc}")

    bootstrap.autocommit = True
    with bootstrap.cursor() as cur:
        cur.execute(f'CREATE DATABASE "{dbname}"')
    bootstrap.close()

    scratch_admin = _with_database(admin_dsn, dbname)
    scratch_app = _with_user(scratch_admin, APP_ROLE, password)

    try:
        conn = psycopg2.connect(scratch_admin, connect_timeout=5)
        conn.autocommit = True
        with conn.cursor() as cur:
            # Same tolerance as ensure_tables(): statements are idempotent and a
            # failure of one must not abort the rest.
            for stmt in (list(DDL_STATEMENTS) + list(MIGRATION_STATEMENTS)
                         + list(AUTHZ_DDL_STATEMENTS)):
                try:
                    cur.execute(stmt)
                except Exception:
                    pass
            for stmt in rls.rls_ddl():
                cur.execute(stmt)  # these must NOT fail — they are the subject
        # Table privileges are per-database, so the role provisioned against the
        # live database has none here until this runs.
        provision(conn, password)
        _seed(conn)
        conn.close()

        yield scratch_app
    finally:
        drop = psycopg2.connect(admin_dsn, connect_timeout=5)
        drop.autocommit = True
        with drop.cursor() as cur:
            cur.execute(
                "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                "WHERE datname = %s AND pid <> pg_backend_pid()",
                (dbname,),
            )
            cur.execute(f'DROP DATABASE IF EXISTS "{dbname}"')
        drop.close()


def _seed(conn) -> None:
    """One class, one sample and one raw upload for each of two tenants.

    `dialect` is left NULL on purpose: the composite foreign key
    `(tenant_id, dialect) -> dialects` is MATCH SIMPLE, so a NULL member leaves
    it unenforced and the fixture does not have to clone a whole vocabulary
    registry to prove a row-visibility property.
    """
    with conn.cursor() as cur:
        # Gieo dữ liệu cho HAI tenant, nên phải ở phạm vi hệ thống — đúng thứ
        # `rls.py` định nghĩa cho việc nền tảng làm xuyên tenant.
        #
        # Trước đây dòng này không cần, và đó mới là điều đáng nói: fixture chạy
        # bằng `admin`, một superuser, nên nó MIỄN TRỪ khỏi RLS và phần gieo dữ
        # liệu chưa bao giờ đi qua chính sách. Khi lượt chạy đổi sang vai chủ sở
        # hữu thường, `FORCE ROW LEVEL SECURITY` lập tức chặn — tức chính sách
        # vẫn đúng, chỉ là bộ kiểm đã đứng ngoài nó suốt.
        #
        # `SET` chứ không `SET LOCAL`: kết nối này đang autocommit, không có
        # giao dịch nào để `LOCAL` bám vào.
        cur.execute(f"SET {rls.SYSTEM_SCOPE_GUC} = '{rls.SYSTEM_SCOPE_ON}'")
        for tenant in (TENANT_A, TENANT_B):
            cur.execute(
                "INSERT INTO tenants(tenant_id, display_name, slug) VALUES (%s, %s, %s) "
                "ON CONFLICT (tenant_id) DO NOTHING",
                (tenant, tenant, tenant),
            )
        for tenant, sample_uid in ((TENANT_A, SAMPLE_A), (TENANT_B, SAMPLE_B)):
            cur.execute(
                "INSERT INTO classes(class_uid, tenant_id, slug, language) "
                "VALUES (%s, %s, %s, 'vn')",
                (f"cls-{tenant}", tenant, f"slug-{tenant}"),
            )
            cur.execute(
                "INSERT INTO samples(sample_uid, tenant_id, class_uid) VALUES (%s, %s, %s)",
                (sample_uid, tenant, f"cls-{tenant}"),
            )
            cur.execute(
                "INSERT INTO raw_uploads(upload_uid, tenant_id) VALUES (%s, %s)",
                (f"upl-{tenant}", tenant),
            )


@pytest.fixture
def app_conn(scratch_db):
    """A connection authenticated as the contained application role."""
    conn = psycopg2.connect(scratch_db, connect_timeout=5)
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT rolsuper OR rolbypassrls FROM pg_roles WHERE rolname = current_user"
            )
            if cur.fetchone()[0]:  # pragma: no cover - would invalidate the suite
                pytest.fail(
                    "the proof connection can bypass RLS; every assertion below "
                    "would pass for the wrong reason"
                )
        yield conn
    finally:
        conn.rollback()
        conn.close()


def _scoped(conn, tenant=None, system=False):
    """Open a transaction bound to a scope, using the production scope SQL."""
    cur = conn.cursor()
    cur.execute(rls._APPLY_SCOPE_SQL, rls.scope_parameters(tenant, system))
    return cur


