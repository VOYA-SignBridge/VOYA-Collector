"""A3 — proof that the tenant boundary is enforced by PostgreSQL, not by us.

Why this file needs a scratch database
--------------------------------------
Proving isolation requires a second tenant with real rows in `samples`,
`classes` and `raw_uploads`. Writing those into the live database is not
acceptable here: a Celery beat reconciles active Postgres rows back into
`dataset/samples.csv` every five minutes, so test fixtures could be copied into
the source of truth and would then need a fresh signed SOT version to remove.

So the proof runs against a database created for the run and dropped after it,
built from the REAL production DDL (`metadata_db.DDL_STATEMENTS`) and the REAL
policy SQL (`rls.rls_ddl()`). Nothing here re-implements the schema or the
policy; if either changes, this suite exercises the new one.

Why it connects as `voya_app` and not `admin`
---------------------------------------------
Superusers bypass row security unconditionally. Run as `admin`, every assertion
below would pass for the wrong reason — the rows would be visible and the
"isolation" would be the test's own WHERE clauses. The suite skips rather than
lies when the contained role is unavailable.

What the app layer contributes
------------------------------
The scope SQL executed here is generated by `rls.scope_parameters()` and
`rls._APPLY_SCOPE_SQL`, the same two things `rls.apply_scope()` uses in
production. `TestApplicationLayerEmitsScope` closes the loop by asserting that
the two functions every metadata query passes through do call `apply_scope`.
"""

from __future__ import annotations

import os
import uuid

import psycopg2
import pytest
from urllib.parse import urlsplit, urlunsplit

from app.storage import rls

TENANT_A = "proof-a"
TENANT_B = "proof-b"

# Hex-10, because `samples_uid_is_hex10` is a live CHECK constraint.
SAMPLE_A = "aaaaaaaa01"
SAMPLE_B = "bbbbbbbb01"


